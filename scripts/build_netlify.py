#!/usr/bin/env python3
"""Build the static Netlify publish directory and host-specific rewrites."""

from pathlib import Path
import re
import shutil
import sys


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "out_spas"
PUBLISH = ROOT / ".netlify-publish"
SLUG = re.compile(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\Z")


def main():
    projects = sorted(path for path in SOURCE.iterdir() if path.is_dir())
    if not projects:
        raise ValueError("out_spas contains no project directories")

    for project in projects:
        if not SLUG.fullmatch(project.name):
            raise ValueError(f"invalid subdomain directory name: {project.name}")
        if not (project / "index.html").is_file():
            raise ValueError(f"missing index.html: {project}")

    if PUBLISH.exists():
        shutil.rmtree(PUBLISH)
    shutil.copytree(SOURCE, PUBLISH)

    rules = ["# Generated by scripts/build_netlify.py; do not edit."]
    for project in projects:
        name = project.name
        host = f"https://{name}.b-cube.kr"
        rules.append(f"{host}/ /{name}/index.html 200!")
        rules.append(f"{host}/* /{name}/:splat 200!")
    (PUBLISH / "_redirects").write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"Prepared {len(projects)} projects in {PUBLISH.relative_to(ROOT)}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        sys.exit(f"Netlify build failed: {error}")
